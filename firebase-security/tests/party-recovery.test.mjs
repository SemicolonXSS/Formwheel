import {readFile} from 'node:fs/promises';
import {before,after,test} from 'node:test';
import {initializeTestEnvironment,assertFails,assertSucceeds} from '@firebase/rules-unit-testing';
import {get,ref,set,update,remove} from 'firebase/database';
import assert from 'node:assert/strict';
let env;
before(async()=>{env=await initializeTestEnvironment({projectId:'demo-formwheel',database:{host:'127.0.0.1',port:9000,rules:await readFile(new URL('../database.rules.json',import.meta.url),'utf8')}});});
after(()=>env?.cleanup());
test('party lifecycle confines membership changes and host controls',async()=>{
 const path='formwheelParty/v1/rooms/ABC234';
 const at=(uid,sub='')=>ref(env.authenticatedContext(uid).database(),path+sub);
 const alice={uid:'alice',name:'Alice'},bob={uid:'bob',name:'Bob'};
 await assertSucceeds(set(at('alice'),{version:1,host:'alice',createdAt:Date.now(),position:0,games:['Quiz','Spy','Button'],members:{alice}}));
 await assertFails(get(ref(env.unauthenticatedContext().database(),path)));
 await assertFails(get(ref(env.authenticatedContext('bob').database(),'formwheelParty/v1/rooms')));
 await assertSucceeds(get(at('bob')));
 await assertFails(set(at('bob','/members/bob'),alice));
 await assertSucceeds(set(at('bob','/members/bob'),bob));
 await assertFails(update(at('bob'),{host:'bob',position:1}));
 await assertFails(remove(at('bob','/members/alice')));
 await assertSucceeds(set(at('alice','/position'),1));
 await assertSucceeds(remove(at('bob','/members/bob')));
 await assertSucceeds(set(at('bob','/members/bob'),bob));
 await assertSucceeds(update(at('alice'),{host:'bob','members/alice':null}));
 await assertFails(remove(at('alice')));
 await assertSucceeds(remove(at('bob')));
 assert.equal((await get(at('bob'))).exists(),false);
 await assertFails(set(at('alice','/members/alice'),alice));
});
