import {readFile} from 'node:fs/promises';
import {after,before,test} from 'node:test';
import {initializeTestEnvironment,assertFails,assertSucceeds} from '@firebase/rules-unit-testing';
import {get,ref,set,update} from 'firebase/database';
let env;
before(async()=>{env=await initializeTestEnvironment({projectId:'demo-formwheel',database:{host:'127.0.0.1',port:9000,rules:await readFile(new URL('../database.rules.json',import.meta.url),'utf8')}});});
after(()=>env?.cleanup());
test('PVP invites admit one guest and keep state and input separated',async()=>{
 const h=env.authenticatedContext('host').database(),g=env.authenticatedContext('guest').database(),o=env.authenticatedContext('other').database();
 const p='formwheelV2/pvpRooms/v2/ABC234';
 const at=(db,sub='')=>ref(db,p+sub);
 const build={weapon:'orb',skill:'dash',speedPoints:1};
 const room={hostUid:'host',status:'waiting',readyHost:false,readyGuest:false,createdAt:Date.now(),updatedAt:Date.now(),hostBuild:build,map:'classic'};
 await assertFails(set(at(g),room));
 await assertSucceeds(set(at(h),room));
 await assertFails(get(ref(g,'formwheelV2/pvpRooms/v2')));
 await assertSucceeds(get(at(g)));
 await assertSucceeds(set(at(g,'/guest'),{uid:'guest',build}));
 await assertFails(set(at(o,'/guest'),{uid:'other',build}));
 await assertSucceeds(set(at(g,'/readyGuest'),true));
 await assertFails(set(at(g,'/readyHost'),true));
 await assertSucceeds(update(at(h),{status:'playing',round:1,readyHost:false,readyGuest:false}));
 const frame={players:[{hp:100},{hp:100}],seq:1,sentAt:Date.now()};
 await assertSucceeds(set(at(h,'/state'),frame));
 await assertFails(set(at(g,'/state'),frame));
 const input={dx:0,dy:0,fireSeq:1,special:false,at:Date.now()};
 await assertFails(set(at(o,'/guestInput'),input));
 await assertSucceeds(set(at(g,'/guestInput'),input));
 await assertSucceeds(set(at(g,'/status'),'ended'));
 await assertFails(set(at(h,'/state'),frame));
});
